_COORD = re.compile(r"@\s*(-?\d+(?:\.\d+)?)\s*[,,]\s*(-?\d+(?:\.\d+)?)")


def locate(text):
    """返回 (经度, 纬度) 或 None。优先自定义坐标,其次最长匹配的城市名,再次省份(省会)。"""
    if not text:
        return None
    m = _COORD.search(text)
    if m:
        lon, lat = float(m.group(1)), float(m.group(2))
        if -180 <= lon <= 180 and -90 <= lat <= 90:
            return lon, lat
    low = text.lower()
    hits = [c for c in CITIES if c in text] + [ALIASES[a] for a in ALIASES if a in low]
    if hits:
        return CITIES[max(hits, key=len)]
    for prov, city in PROVINCES.items():
        if prov in text:
            return CITIES[city]
    return None


def label(text):
    """地图上显示的地点名称(去掉自定义坐标部分)。"""
    return _COORD.sub("", text or "").strip() or text
